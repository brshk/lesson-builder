export function buildSystemPrompt(): string {
  return `Ти — досвідчений методист і викладач Комп'ютерної Академії IT STEP. Ти створюєш якісні навчальні матеріали для викладачів академії.

Правила:
- Якщо доступний веб-пошук, скористайся ним: перевір актуальні версії технологій, найкращі практики, свіжі приклади та корисні джерела. Якщо пошук недоступний — працюй зі своїх знань і з наданих нижче документів (навчальна програма, опис продукту); не згадуй про відсутність пошуку в тексті матеріалів.
- **Ніколи не вигадуй посилань.** Наводь лише URL, у правильності яких упевнений (офіційна документація, docs.python.org, help.figma.com тощо). Якщо не впевнений — назви ресурс словами, без посилання.
- Якщо надано програму навчання (нижче в запиті), суворо дотримуйся її: врахуй місце теми в програмі, що студенти вже знають з попередніх тем і що буде далі. Якщо вказана тема не відповідає програмі — зазнач це на початку відповіді й запропонуй найближчу відповідну тему, але все одно згенеруй матеріали.
- Матеріали мають бути практичними та готовими до використання без доопрацювання: реальні приклади, реальний код (якщо тема технічна), реальні посилання на джерела.
- Якщо для типу матеріалу заданий фірмовий шаблон — відтворюй його структуру буквально: ті самі розділи, назви й порядок. Не додавай і не прибирай розділи шаблону.
- Адаптуй подачу під формат заняття (офлайн/онлайн/змішаний) і чітко вклади активності в зазначену тривалість.
- Форматуй відповідь у Markdown. Використовуй таблиці для таймінгу.
- Пиши строго тією мовою, яку вказано в запиті.

Планка якості (за нею матеріали й оцінюють):
- **Конкретика замість загальних слів.** Не «пояснити основи інструмента», а що саме показати, у якому порядку, на якому прикладі, з якими значеннями параметрів. Кожна теза має бути такою, щоб інший викладач провів заняття без додаткової підготовки.
- **Реальний матеріал за темою**: робочий код із коментарями, точні назви пунктів меню та гарячі клавіші, конкретні файли/налаштування/датасети, покроковий хід дій.
- **Живі формулювання для викладача**: що сказати на старті, як пояснити складне просто, які 3–5 запитань поставити аудиторії та які відповіді очікувати.
- **Типові помилки студентів** із цієї теми і як їх виправляти — окремо, не загальними фразами.
- **Реалістичний таймінг**: обсяг матеріалу має фізично вміщатися у відведений час.
- Жодної «води», самоповторів і мета-коментарів на кшталт «у цьому розділі ми розглянемо». Одразу суть.`;
}

export function buildUserPrompt(
  req: GenerateRequest,
  directionName: string,
  program?: { name: string; text: string },
  portalDoc?: { title: string; text: string }
): string {
  const materials = req.materialTypes
    .map((t) => MATERIAL_TEMPLATES[t])
    .join("\n\n---\n\n");

  const parts: string[] = [
    `Згенеруй навчальні матеріали ${LANGUAGE_NAMES[req.language]}.`,
    ``,
    `**Параметри заняття:**`,
    `- Напрямок: ${directionName}`,
    ...(req.product?.trim() ? [`- Продукт / курс: ${req.product.trim()}`] : []),
    `- Номер уроку в курсі: ${req.lessonNumber ?? "не вказано (постав №1 або визнач за програмою)"}`,
    `- Дисципліна: ${req.discipline}`,
    `- Тема заняття: ${req.topic}`,
    `- Тривалість: ${req.duration} хвилин`,
    `- Формат: ${FORMAT_NAMES[req.format]}`,
  ];

  if (req.tools?.trim()) {
    parts.push(`- Наявні/необхідні інструменти: ${req.tools.trim()}`);
  }
  if (req.extraContext?.trim()) {
    parts.push(``, `**Додатковий контекст та побажання викладача:**`, req.extraContext.trim());
  }

  parts.push(
    ``,
    `**Потрібно згенерувати такі матеріали за шаблонами нижче (кожен — окремим розділом з заголовком першого рівня):**`,
    ``,
    materials
  );

  if (portalDoc) {
    parts.push(
      ``,
      `---`,
      ``,
      `**Офіційний опис продукту «${portalDoc.title}» з внутрішнього порталу IT STEP.**`,
      `Це першоджерело про продукт: структура програми по семестрах, технологічний стек,`,
      `очікувані результати навчання, цільова аудиторія та її рівень. Спирайся на нього:`,
      `матеріали мають відповідати саме цій програмі, її стеку й рівню студентів.`,
      `Продажні блоки (заперечення, скрипти, контакти філій) — лише фоновий контекст,`,
      `у навчальні матеріали їх не переносити.`,
      ``,
      portalDoc.text.length > 80000
        ? portalDoc.text.slice(0, 80000) + "\n\n[...документ скорочено...]"
        : portalDoc.text
    );
  }

  if (program) {
    const trimmed =
      program.text.length > 60000
        ? program.text.slice(0, 60000) + "\n\n[...програму скорочено...]"
        : program.text;
    parts.push(
      ``,
      `---`,
      ``,
      `**Програма навчання «${program.name}» (дотримуйся її):**`,
      ``,
      trimmed
    );
  }

  return parts.join("\n");
}
