export function buildEditUserPrompt(req: EditRequest): string {
  const instruction = req.action
    ? EDIT_ACTIONS[req.action]
    : (req.instruction ?? "").trim();

  const parts: string[] = [
    `### ${LANGUAGE_RULE[req.language]}`,
    ``,
    `**Заняття:** ${req.discipline} — ${req.topic}`,
    `**Тривалість:** ${req.duration} хв · **Формат:** ${FORMAT_NAMES[req.format]}`,
    ...(req.product?.trim() ? [`**Курс:** ${req.product.trim()}`] : []),
    ...(req.tools?.trim() ? [`**Інструменти:** ${req.tools.trim()}`] : []),
    ...groupBlock(req.group),
  ];

  if (req.outline?.length) {
    parts.push(
      ``,
      `**Структура заняття цілком** (для контексту, змінювати не треба):`,
      ...req.outline.map((h) => `- ${h}`)
    );
  }

  if (req.scope === "block") {
    parts.push(
      ``,
      `---`,
      ``,
      `**ЗАВДАННЯ:** ${instruction}`,
      ``,
      `**Фрагмент, який треба переробити** (поверни ЛИШЕ його нову версію):`,
      ``,
      req.blockText ?? ""
    );
  } else {
    parts.push(
      ``,
      `---`,
      ``,
      `**ЗАВДАННЯ від викладача:** ${instruction}`,
      ``,
      `Переробле́ний документ поверни ПОВНІСТЮ, зі збереженням структури й усіх розділів.`,
      `Змінюй лише те, що стосується завдання; решту залиш як є, слово в слово.`,
      ``,
      `**Поточний документ:**`,
      ``,
      req.documentText ?? ""
    );
  }

  parts.push(``, `---`, ``, `### ${LANGUAGE_RULE[req.language]}`);
  return parts.join("\n");
}

