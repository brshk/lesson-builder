/** Блок промпту про конкретну групу — основа диференціації матеріалів. */
function groupBlock(g?: GroupContext): string[] {
  if (!g) return [];
  const facts: string[] = [];

  if (g.ageFrom || g.ageTo) {
    const age =
      g.ageFrom && g.ageTo
        ? g.ageFrom === g.ageTo
          ? `${g.ageFrom} років`
          : `${g.ageFrom}–${g.ageTo} років`
        : `${g.ageFrom ?? g.ageTo} років`;
    facts.push(`- Вік студентів: ${age}`);
  }
  if (g.students) facts.push(`- Кількість студентів у групі: ${g.students}`);
  if (g.level) facts.push(`- Рівень групи: ${g.level === "weak" ? "слабкий" : g.level === "strong" ? "сильний" : "змішаний"}`);
  if (g.hardware?.trim()) facts.push(`- Обладнання: ${g.hardware.trim()}`);
  if (g.priorKnowledge?.trim()) facts.push(`- Що група вже знає: ${g.priorKnowledge.trim()}`);

  if (!facts.length) return [];

  const rules: string[] = [
    ``,
    `**Профіль групи — матеріали мають бути зроблені саме під неї:**`,
    ...facts,
    ``,
    `Як це враховувати:`,
  ];

  if (g.level) rules.push(`- ${LEVEL_RULES[g.level]}`);
  if (g.ageFrom || g.ageTo) {
    const age = g.ageTo ?? g.ageFrom ?? 0;
    rules.push(
      age <= 10
        ? `- Вік малий: приклади з ігор, мультфільмів і побуту дитини; блоки активності по 5–7 хвилин зі зміною діяльності; жодних довгих пояснень поспіль; інструкції короткими реченнями.`
        : age <= 14
          ? `- Підлітковий вік: приклади з ігор, соцмереж, YouTube і того, чим користуються самі; зміна діяльності кожні 10–12 хвилин; змагальні елементи працюють краще за лекцію.`
          : `- Дорослі/старші студенти: доречні професійний контекст, зв'язок із реальними задачами роботодавця та кар'єрою; можна довші самостійні блоки.`
    );
  }
  if (g.students) {
    rules.push(
      g.students >= 15
        ? `- Група велика (${g.students}): врахуй, що викладач фізично не встигне підійти до кожного. Передбач роботу в парах/командах, спільну перевірку й самоперевірку за чек-лістом.`
        : `- Група невелика (${g.students}): можлива індивідуальна увага, розбір роботи кожного, обговорення колом.`
    );
  }
  if (g.hardware?.trim()) {
    rules.push(
      `- Усі активності мають бути виконувані саме на цьому обладнанні. Не пропонуй того, що на ньому не запуститься; гарячі клавіші та шляхи вказуй для цієї платформи.`
    );
  }
  if (g.priorKnowledge?.trim()) {
    rules.push(`- Не витрачай час заняття на те, що група вже знає, — спирайся на це як на фундамент.`);
  }

  return rules;
}

